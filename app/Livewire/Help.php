            }
            if (isset($s['role'])) {
                return $user->hasRole($s['role']);
            }

            if ($s['can'] === null) {
                return true;
            }

            return collect((array) $s['can'])->contains(fn ($p) => $user->can($p));
        })->values()->all();

        return view('livewire.help', compact('sections'));
    }

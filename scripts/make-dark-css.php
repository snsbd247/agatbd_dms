<?php
// Builds resources/css/dark.css from the palette Tailwind actually emits.
// Run after `npm run build`:  php scripts/make-dark-css.php   then build again.
chdir(dirname(__DIR__));
$css = file_get_contents(glob('public/build/assets/app-*.css')[0]);
preg_match_all('/--color-([a-z]+)-(\d+):([^;}]+)/', $css, $m, PREG_SET_ORDER);
$pal = [];
foreach ($m as [$all, $hue, $shade, $val]) $pal[$hue][$shade] = trim($val);

$neutral = [ // light value -> dark value, for slate and gray
    '50' => '#162033', '100' => '#0b1120', '200' => '#28354a', '300' => '#3a475c',
    '400' => '#7d8ba1', '500' => '#98a5b8', '600' => '#b5c0cf', '700' => '#cbd5e1',
    '800' => '#e2e8f0', '900' => '#f1f5f9', '950' => '#f8fafc',
];

$dark = $keep = [];
foreach ($pal as $hue => $shades) {
    foreach ($shades as $s => $v) {
        if (in_array($hue, ['slate', 'gray'], true)) {
            $new = $neutral[$s] ?? null;
        } else {
            $new = match ((string) $s) {
                '50' => "color-mix(in oklab, {$shades['500']} 12%, transparent)",
                '100' => "color-mix(in oklab, {$shades['500']} 20%, transparent)",
                '200' => "color-mix(in oklab, {$shades['500']} 35%, transparent)",
                '700' => $shades['300'],
                '800' => $shades['200'],
                '900' => $shades['100'],
                default => null,
            };
        }
        if ($new !== null) {
            $dark[] = "    --color-$hue-$s: $new;";
            $keep[] = "    --color-$hue-$s: $v;";
        }
    }
}

$text = [];
foreach ($pal as $hue => $shades) {
    if (in_array($hue, ['slate', 'gray'], true) || ! isset($shades['400'])) continue;
    $text[] = "html.dark .text-$hue-600:not(.dark-keep *), html.dark .text-$hue-500:not(.dark-keep *) { color: {$shades['400']}; }";
}

$out = "/* Dark mode. GENERATED by scripts/make-dark-css.php from Tailwind's palette;\n"
    ."   to change the look, edit that script rather than this file by hand.\n\n"
    ."   How it works: under html.dark every palette colour is remapped (light\n"
    ."   greys become dark, pale tints become translucent, deep text shades\n"
    ."   become light), so the existing utility classes in every view switch\n"
    ."   theme without per-view dark: classes. Elements that are already dark\n"
    ."   (the sidebar, gradient banners) carry .dark-keep, which restores the\n"
    ."   original palette inside them. */\n\n"
    ."html.dark {\n    color-scheme: dark;\n".implode("\n", $dark)."\n}\n\n"
    ."html.dark .dark-keep {\n".implode("\n", $keep)."\n}\n\n"
    ."html.dark .bg-white:not(.dark-keep *) { background-color: #111a2d; }\n"
    ."html.dark .hover\\:bg-white:hover:not(.dark-keep *) { background-color: #1a2438; }\n"
    ."html.dark .shadow, html.dark .shadow-sm, html.dark .shadow-md, html.dark .shadow-lg { --tw-shadow-color: rgb(0 0 0 / 0.5); }\n"
    ."html.dark input::placeholder, html.dark textarea::placeholder { color: #64748b; }\n"
    ."html.dark select option { background-color: #111a2d; color: #e2e8f0; }\n"
    ."html.dark input[type=date]::-webkit-calendar-picker-indicator { filter: invert(0.8); }\n"
    .implode("\n", $text)."\n";

file_put_contents('resources/css/dark.css', $out);
echo count($dark)." vars, ".count($text)." text overrides\n";
